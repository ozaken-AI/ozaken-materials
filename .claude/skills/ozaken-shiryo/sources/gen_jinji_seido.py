def transform(page):
    page = cover_lead(replace_chapters(page,build()),COVER_COPY)
    toc = Tree(page).root.first('oz-toc')
    if toc:
        groups = [('仕事の分担を考える','第1–3章'),('採用で見極める力','第4章'),
                  ('配置と育成を組み合わせる','第5章'),('役割・評価・報酬をつなぐ','第6–9章'),
                  ('制度の移行と社外への説明','第10–12章'),('最初の90日と持ち帰る問い','第13–14章')]
        content = '<div class="oz-toc"><div class="inner"><span class="eyebrow">Contents</span>'
        content += '<p class="oz-toc-ttl">この資料の流れ</p><ol class="oz-toc-list" aria-label="この資料の流れ">'
        content += ''.join(f'<li><b>{i:02d}</b><span>{label}</span><i>{span}</i></li>'
                           for i,(label,span) in enumerate(groups,1))
        content += '</ol></div></div>'
        page = page[:toc.start]+content+page[toc.end:]
    return metadata(page)


transform.cover_copy = COVER_COPY
transform.public_metadata = metadata

