    for k in keys:
        r = dict(ROLES[k])
        r['uid'] = k[:3]
        body = build(r)
        path = '/tmp/body_role_%s.html' % k
        open(path, 'w', encoding='utf-8').write(body)
        print('── %s（%d字）' % (k, len(body)))
        cmd = ['python3', os.path.join(HERE, 'publish.py'), path, r['slug'], '--update']
        p = subprocess.run(cmd, capture_output=True, text=True, cwd='/home/user/ozaken-materials')
        print((p.stdout + p.stderr).strip())
        if p.returncode:
            sys.exit('%s で落ちました' % k)


