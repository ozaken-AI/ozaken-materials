def dechip(cs):
    """カードの自動採番と重なる、数字だけのチップを落とす。

    cards() は 01〜 の丸バッジを自前で振る。そこへ
    <span class="mth">01</span> を足していたので、同じ番号が2つ並んでいた
    """
    return [(re.sub(r'<span class="mth">\d+</span>\s*', '', h), b) for h, b in cs]


