            rows(['現場の声','共同化で確かめること','次に直すもの'],[
                ('申請先が分からない','完了するには何が必要か','表出化：回答の型に申請先を追加'),
                ('古い規程で案内された','正本はどれか 更新日はいつか','連結化：参照先と更新方法を修正'),
                ('例外をそのまま断定された','どの条件なら担当へ確認するか','表出化：確認へ回す条件を追加')]),
