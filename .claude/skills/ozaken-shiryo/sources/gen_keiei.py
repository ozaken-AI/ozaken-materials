# **面の地の色は、並び順から機械的に振る。**
# 節を1つ差し込むたびに、それ以降の light / navy を全部書き換えなければ
# ならなかった。1か所でも直し忘れると「同じ背景が連続」で公開が止まる。
# 節番号と図版番号を後から振り直しているのと、これは同じ種類の仕事。
# 先頭を light にし、交互に置けば、末尾（締めの面）は必ず navy になる
# ── 本文が奇数本という規約が守られているかぎり。
_t = [0]
def _tone(m):
    _t[0] += 1
    return '<section class="sec-%s"' % ('light' if _t[0] % 2 else 'navy')
_body = _re.sub(r'<section class="sec-(?:light|navy)"', _tone, _body)

_n = [0]
def _sec(m):
    _n[0] += 1
    return 'Section %02d' % _n[0]
_body = _re.sub(r'Section \d+', _sec, _body)
_f = [0]
def _fig(m):
    _f[0] += 1
    return 'Fig.%d' % _f[0]
_body = _re.sub(r'Fig\.\d+', _fig, _body)
